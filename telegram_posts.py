def tip_of_day(offset: int = 0) -> str:
    """پست آموزشی روز (چرخشی بر اساس تاریخ؛ offset برای گرفتن روزهای بعد)."""
    day = datetime.now(timezone.utc).toordinal() + offset
    tip = TIPS[day % len(TIPS)]
    return (
        f"🎓 *آموزش روز | {tip['title']}*\n\n"
        f"{tip['body']}\n\n"
        f"📖 منبع: {tip['source']}\n"
        f"{DISCLAIMER}"
    )


# ---------- رصد هفتگی شواهد ----------
def weekly_digest(days: int = 7, limit: int = 10) -> str | None:
    """خلاصه‌ی مقالات جدید PubMed را می‌سازد؛ در خطا None برمی‌گرداند."""
    try:
        from monitoring.article_watcher import fetch
        papers = fetch(days=days, limit=limit)
    except Exception as e:
        log.warning("دریافت مقالات PubMed ناموفق بود: %s", e)
        return None
    if not papers:
        return None
    lines = [
        f"📰 *رصد هفتگی شواهد علمی — تشخیص دوگانه*\n",
        f"{len(papers)} مقاله‌ی جدید PubMed در {days} روز گذشته:\n",
    ]
    for i, p in enumerate(papers, 1):
        title = (p.get("title") or "").strip()
        lines.append(f"{i}. {title}")
        lines.append(f"   🔗 {p.get('url')}")
    lines += [
        "\nاین مقالات برای بازبینی و افزودن به پایگاه دانش دستیار ثبت می‌شوند.",
        DISCLAIMER,
    ]
    return "\n".join(lines)
